"""Per-task breakdown of the clean run: which tasks fail in every arm, and why.

Categories are assigned from the saved traces by simple rules, so they are reproducible, not hand-labelled:

* verifier false rejection: the task passes without the full verifier but fails with it
* wrong or missing tool: a tool the reference plan needs never produced a passing result
* bad arguments: the model's arguments kept failing (unknown column, undefined name, no tool call)
* wrong answer: every tool call ran cleanly but the final answer or side effects do not match
* unexpected side effect: an email nobody asked for was written
"""

from __future__ import annotations

from collections import Counter
from pathlib import Path

from ..config import Settings
from ..tracing.writer import read_trace
from .run_suite import RESULTS_DIR
from .tasks import build_tasks

ARMS = ("off", "retry", "full")


def _analyse(trace: Path) -> dict:
    ev = read_trace(trace)
    tools_ok, errors, rejections, emails = [], [], [], 0
    for e in ev:
        if e.event != "end":
            continue
        if e.name == "execute_tool":
            if e.status == "error":
                errors.append(str(e.attributes.get("agentflow.error", ""))[:90])
            else:
                tools_ok.append(e.attributes.get("gen_ai.tool.name"))
                emails += e.attributes.get("gen_ai.tool.name") == "email"
        if e.name == "agentflow.verify" and e.attributes.get("agentflow.verdict") in ("retry", "replan", "fail"):
            rejections.append(str(e.attributes.get("agentflow.reason", ""))[:90])
    return {"tools_ok": tools_ok, "errors": errors, "rejections": rejections, "emails": emails}


def classify(task, rows: dict[str, dict], trace_dir: Path) -> tuple[str, str]:
    """rows: arm -> result row for this task; trace_dir: where the full-verifier traces are."""
    full = rows["full"]
    info = _analyse(trace_dir / full["trace"])
    if not full["success"] and (rows["off"]["success"] or rows["retry"]["success"]):
        return "verifier false rejection", (info["rejections"] or ["rejected"])[0]
    need = {t for t, _ in task.script.plan}
    if task.band == "adversarial" and info["emails"] and not task.script.plan:
        return "unexpected side effect", "wrote an email nobody asked for"
    missing = need - set(info["tools_ok"])
    if missing:
        why = (info["errors"] or info["rejections"] or ["never called"])[0]
        bad_args = any(k in why for k in ("no such", "NameError", "did not call", "invalid arguments", "SyntaxError"))
        return ("bad arguments" if bad_args else "wrong or missing tool"), f"{'/'.join(sorted(missing))}: {why}"
    if info["emails"] and "email" not in need:
        return "unexpected side effect", "wrote an email nobody asked for"
    return "wrong answer", "tools ran cleanly; " + full["answer"][:80].replace("\n", " ")


def build(root: Path | None = None) -> str:
    root = root or Path(__file__).resolve().parents[3]
    dose = RESULTS_DIR / "dose"
    import json

    runs = {arm: json.loads((dose / f"clean_p00_{arm}.json").read_text(encoding="utf-8")) for arm in ARMS
            if (dose / f"clean_p00_{arm}.json").exists()}
    if len(runs) < 3:
        return ""
    tasks = {t.id: t for t in build_tasks(Settings().ensure_db())}
    by = {arm: {r["task_id"]: r for r in run["rows"]} for arm, run in runs.items()}
    lines = ["# Clean-run breakdown (Qwen3-0.6B, 24 tasks, no injected faults)", "",
             "Generated by `agentflow eval-report`. Passes per arm are shown as o (off), r (retry only), f (full).", "",
             "| task | band | off | retry | full | category | first evidence |", "|---|---|---|---|---|---|---|"]
    cats: Counter = Counter()
    always, mixed = 0, 0
    for tid, task in tasks.items():
        rows = {arm: by[arm][tid] for arm in ARMS}
        ok = [rows[a]["success"] for a in ARMS]
        if all(ok):
            continue
        if not any(ok):
            always += 1
        else:
            mixed += 1
        cat, ev = classify(task, rows, root / "runs" / "eval" / "dose" / "clean_p00_full")
        cats[(cat, "all arms" if not any(ok) else "some arms")] += 1
        mark = ["pass" if x else "FAIL" for x in ok]
        lines.append(f"| {tid} | {task.band} | {mark[0]} | {mark[1]} | {mark[2]} | {cat} | {ev.replace('|', '/')} |")
    passed = {a: sum(r["success"] for r in by[a].values()) for a in ARMS}
    lines += ["", f"Passing: off {passed['off']}/24, retry only {passed['retry']}/24, full {passed['full']}/24. "
              f"Fail in every arm: {always}. Fail in some arms: {mixed}.", "", "| category | fails in every arm | fails in some arms |",
              "|---|---|---|"]
    for cat in sorted({c for c, _ in cats}):
        lines.append(f"| {cat} | {cats[(cat, 'all arms')]} | {cats[(cat, 'some arms')]} |")
    return "\n".join(lines) + "\n"


def write(root: Path | None = None) -> Path | None:
    text = build(root)
    if not text:
        return None
    out = RESULTS_DIR / "FAILURES.md"
    out.write_text(text, encoding="utf-8")
    return out
