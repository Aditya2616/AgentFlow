"""Turn saved result files into evals/results/SUMMARY.md (the numbers quoted in the README)."""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

from .run_suite import RESULTS_DIR
from .stats import mcnemar_exact, wilson

BANDS = [("single", "single tool"), ("two_step", "two steps"), ("multi", "three steps"),
         ("adversarial", "adversarial")]


def _pct(k: int, n: int) -> str:
    lo, hi = wilson(k, n)
    return f"{k}/{n} = {100 * k / n:.0f}% [{100 * lo:.0f}, {100 * hi:.0f}]" if n else "-"


def load(results_dir: Path = RESULTS_DIR) -> list[dict]:
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted(results_dir.glob("*.json"))]


def build_report(results_dir: Path = RESULTS_DIR) -> str:
    runs = load(results_dir)
    lines = ["# Evaluation summary", "",
             "Generated by `agentflow eval-report` from the JSON files in this folder. "
             "Intervals are 95% Wilson score intervals.", ""]
    lines += ["## Overall", "", "| configuration | model | device, dtype | verifier | faults | success | mean seconds/task |",
              "|---|---|---|---|---|---|---|"]
    for r in runs:
        mean = sum(x["seconds"] for x in r["rows"]) / max(1, len(r["rows"]))
        lines.append(
            f"| {r['name']} | {r['model']} | {r.get('device', 'n/a')}, {r.get('dtype', 'n/a')} | {'on' if r['verifier'] else 'off'} | {r['fault_p']:.0%} | "
            f"{_pct(r['successes'], r['n'])} | {mean:.1f} |"
        )
    lines += ["", "## By task band", "", "| configuration | " + " | ".join(b[1] for b in BANDS) + " |",
              "|---|" + "---|" * len(BANDS)]
    for r in runs:
        cells = []
        for key, _ in BANDS:
            rows = [x for x in r["rows"] if x["band"] == key]
            cells.append(_pct(sum(x["success"] for x in rows), len(rows)))
        lines.append(f"| {r['name']} | " + " | ".join(cells) + " |")

    groups: dict[tuple, dict[bool, dict]] = defaultdict(dict)
    for r in runs:
        groups[(r["model"], r["fault_p"], r["seeds"])][r["verifier"]] = r
    pairs = {k: v for k, v in groups.items() if True in v and False in v}
    if pairs:
        lines += ["", "## Verifier on vs off (paired: same task, same seed)", "",
                  "| model | faults | both pass | only with verifier | only without | neither | exact p |",
                  "|---|---|---|---|---|---|---|"]
        for (model, fp, _), v in pairs.items():
            on = {(x["task_id"], x["seed"]): x["success"] for x in v[True]["rows"]}
            off = {(x["task_id"], x["seed"]): x["success"] for x in v[False]["rows"]}
            keys = on.keys() & off.keys()
            both = sum(on[k] and off[k] for k in keys)
            only_on = sum(on[k] and not off[k] for k in keys)
            only_off = sum(off[k] and not on[k] for k in keys)
            neither = sum(not on[k] and not off[k] for k in keys)
            lines.append(f"| {model} | {fp:.0%} | {both} | {only_on} | {only_off} | {neither} | "
                         f"{mcnemar_exact(only_on, only_off):.4f} |")
    lines += ["", "## Recovery and failure detail", "",
              "| configuration | tasks with a retry | tasks with a replan | plan fallbacks | verifier would have flagged (off runs) |",
              "|---|---|---|---|---|"]
    for r in runs:
        rows = r["rows"]
        lines.append(
            f"| {r['name']} | {sum(1 for x in rows if x['retries'])} | {sum(1 for x in rows if x['replans'])} | "
            f"{sum(1 for x in rows if x['plan_fallback'])} | {sum(1 for x in rows if x['would_flag'])} |"
        )
    lines += ["", "## Failed tasks", ""]
    for r in runs:
        failed = [f"{x['task_id']}" + (f" (seed {x['seed']})" if r["seeds"] > 1 else "")
                  for x in r["rows"] if not x["success"]]
        lines.append(f"- **{r['name']}**: {', '.join(failed) if failed else 'none'}")
    return "\n".join(lines) + "\n"


def write_report(results_dir: Path = RESULTS_DIR) -> Path:
    out = results_dir / "SUMMARY.md"
    out.write_text(build_report(results_dir), encoding="utf-8")
    return out
